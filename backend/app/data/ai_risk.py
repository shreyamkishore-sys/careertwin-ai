def resilience_score(
    components: dict[str, int | float],
    automation_exposure: int | float,
) -> int:
    score = sum(
        float(components[factor]) * weight
        for factor, weight in AI_RESILIENCE_WEIGHTS.items()
        if factor != "lower_task_exposure"
    )
    score += (100 - float(automation_exposure)) * AI_RESILIENCE_WEIGHTS["lower_task_exposure"]
    return round(score)


def impact_label(score: int) -> str:
    if score <= 30:
        return "Low"
    if score <= 60:
        return "Moderate"
    if score <= 80:
        return "High"
    return "Very high"
